let service = null
let bound = null

// `locale` is the DSH locale service; without one, copy stays English.
export function installLocale(locale) {
  if (!locale || typeof locale.register !== 'function' || typeof locale.bind !== 'function') return () => {}
  service = locale
  bound = locale.bind(NAMESPACE)
  const offs = [locale.register(NAMESPACE, 'zh', ZH), locale.register(NAMESPACE, 'vi', VI)]
  // Older DSH versions only ship zh and en: without addLanguage, the vi
  // dictionary still works wherever the host offers a vi locale.
  if (typeof locale.addLanguage === 'function') {
    try { offs.push(locale.addLanguage({ id: 'vi', label: 'Tiếng Việt', fallback: 'en' })) } catch { /* already registered */ }
  }
  return () => {
    if (service === locale) { service = null; bound = null }
    for (const off of offs) if (typeof off === 'function') off()
  }
}

export function t(key, params) {
  return bound ? bound(key, params) : fill(key, params)
}

// A message from the host, in the interface language.
const HOST_TEXT = { zh: [ZH, HOST_ERRORS], vi: [VI, HOST_ERRORS_VI] }

export function hostText(message) {
  const entry = HOST_TEXT[language().split('-')[0]]
  if (!entry) return message
  const [dict, patterns] = entry
  if (Object.hasOwn(dict, message)) return t(message)
  for (const [pattern, template] of patterns) {
    if (pattern.test(message)) return message.replace(pattern, template)
  }
  return message
}

// The active DSH language tag, for dates and times.
export function language() {
  const active = service?.getLocale?.().active
  return typeof active === 'string' ? active : 'en'
}

